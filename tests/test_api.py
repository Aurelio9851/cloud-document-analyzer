import json
import urllib.request
import urllib.error

API_URL = (
    "https://yj59ygsyib.execute-api.eu-west-1.amazonaws.com"
    "/upload-url"
)

payload = {
    "filename": "api-gateway-test.txt"
}

request = urllib.request.Request(
    API_URL,
    data=json.dumps(payload).encode("utf-8"),
    headers={"Content-Type": "application/json"},
    method="POST"
)

try:
    with urllib.request.urlopen(request) as response:
        result = json.loads(response.read().decode("utf-8"))

        print("HTTP status:", response.status)
        print("Object key:", result.get("object_key"))
        print("Expires in:", result.get("expires_in"), "seconds")

        if response.status == 200 and result.get("upload_url"):
            print("API Gateway test successful.")

except urllib.error.HTTPError as error:
    print("HTTP error:", error.code)
    print(error.read().decode("utf-8"))

upload_url = result["upload_url"]

document_content = """
Cloud Document Analyzer

This document was uploaded through API Gateway.
The upload URL was generated by AWS Lambda.
The document was uploaded directly to Amazon S3.
"""

upload_request = urllib.request.Request(
    upload_url,
    data=document_content.encode("utf-8"),
    headers={"Content-Type": "text/plain"},
    method="PUT"
)

with urllib.request.urlopen(upload_request) as response:
    print("S3 upload status:", response.status)
    print("Upload completed successfully.")